import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { importCadText } from '../cad-import.mjs';
import { partsFromShapeJson, serializeShapeJson } from '../parts-shapes.mjs';
const panels = [{material:'MDF',thickness:18}];
const options = {panels, fileName:'test.dxf'};
const fixture = readFileSync(new URL('../examples/CAD-轮廓与内孔示例.dxf',import.meta.url),'utf8');
const drawing = (entities, blocks='') => `0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n4\n0\nENDSEC\n${blocks ? `0\nSECTION\n2\nBLOCKS\n${blocks}0\nENDSEC\n` : ''}0\nSECTION\n2\nENTITIES\n${entities}0\nENDSEC\n0\nEOF\n`;
const line = (a,b) => `0\nLINE\n10\n${a[0]}\n20\n${a[1]}\n11\n${b[0]}\n21\n${b[1]}\n`;
const poly = (points) => `0\nLWPOLYLINE\n90\n${points.length}\n70\n1\n${points.map(p=>`10\n${p[0]}\n20\n${p[1]}\n`).join('')}`;
const rect = poly([[0,0],[100,0],[100,60],[0,60]]);
const result = importCadText(fixture,options);
assert.deepEqual(result.parts.map(p=>[p.length,p.width,p.shape.holes.length]),[[120,80,1],[100,60,0]]);
assert.deepEqual(result.warnings,[]);
assert.equal(result.parts[0].material,'MDF');
assert.equal(result.parts[0].cadSource.targetYAxis,'down');
assert.deepEqual(result.parts[0].cadSource.origin,[0,-80]);
assert.deepEqual(result.parts[1].cadSource.origin,[200,-60],'整图预览必须保留件间位置，局部轮廓仍归一化');
const saved = partsFromShapeJson(serializeShapeJson(result.parts),{panels});
assert.deepEqual(saved[0].cadSource,result.parts[0].cadSource);
assert.deepEqual(saved[0].shape,result.parts[0].shape);
const scaled = importCadText(drawing(rect),{...options,unitOverride:'inch'}).parts[0];
assert.equal(scaled.length,2540); assert.equal(scaled.width,1524);
const chain = drawing(line([0,0],[100,0])+line([100,60],[100,0])+line([0,60],[100,60])+line([0,0],[0,60]));
assert.equal(importCadText(chain,options).parts[0].length,100);
assert.throws(()=>importCadText(drawing(line([0,0],[100,0])),options),/开放或分叉/);
assert.throws(()=>importCadText(drawing(rect+rect),options),/相交、相接或重复/);
assert.throws(()=>importCadText(drawing('0\nREGION\n'),options),/不支持的CAD图元/);
const withViewport = importCadText(drawing(rect + '0\nVIEWPORT\n10\n0\n20\n0\n40\n1000\n41\n1000\n'), options);
assert.equal(withViewport.parts.length, 1);
assert.deepEqual(withViewport.parts[0].shape, importCadText(drawing(rect), options).parts[0].shape);
assert.ok(withViewport.warnings.some(message => message.includes('已忽略布局视口 VIEWPORT')));
assert.throws(()=>importCadText(drawing('0\nPOLYLINE\n70\n1\n'),options),/SEQEND/);
assert.throws(()=>importCadText(drawing(rect.replace('70\n1','43\n2\n70\n1')),options),/线宽/);
assert.throws(()=>importCadText(fixture,{...options,fileName:'test.dwg'}),/DWG/);
assert.throws(()=>importCadText(drawing('0\nSPLINE\n70\n4\n'),options),/有理SPLINE/);
const circle = importCadText(drawing('0\nCIRCLE\n10\n0\n20\n0\n40\n12\n'),options).parts[0];
assert.ok(Math.abs(circle.length-24)<1e-8); assert.ok(Math.abs(circle.width-24)<1e-8);
const blocks = `0\nBLOCK\n2\nR\n70\n0\n10\n10\n20\n20\n${poly([[10,20],[110,20],[110,80],[10,80]])}0\nENDBLK\n`;
const blockPart = importCadText(drawing('0\nINSERT\n2\nR\n10\n500\n20\n200\n41\n2\n42\n3\n50\n90\n',blocks),options).parts[0];
assert.ok(Math.abs(blockPart.length-180)<1e-8); assert.ok(Math.abs(blockPart.width-200)<1e-8);
const islands = importCadText(drawing(poly([[0,0],[100,0],[100,100],[0,100]])+poly([[10,10],[90,10],[90,90],[10,90]])+poly([[20,20],[30,20],[30,30],[20,30]])),options);
assert.deepEqual(islands.parts.map(p=>p.shape.holes.length),[1,0]);
console.log('CAD import tests passed: contours, holes/islands, units, blocks, persistence and rejection of unsafe geometry.');
