import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { optimizeCuttingPlan } from '../engine.mjs';
import { fillPolygonSheet } from '../polygon-nesting.mjs';
import { shapesOverlap } from './fixtures/polygon-geometry-reference.mjs';
const project=JSON.parse(readFileSync(new URL('./fixtures/nesting-spare-space.json',import.meta.url)));
const progress=[];
const result=optimizeCuttingPlan(project,{onProgress:p=>progress.push(structuredClone(p))});
assert.equal(result.stats.placedCount,12);assert.equal(result.stats.usedPanels,1,'外框、格栅、10件小件必须继续补排在同一张板');
assert.ok(progress.length>=12);assert.ok(progress.some(p=>p.layouts.reduce((n,l)=>n+l.placements.length,0)===1));
assert.equal(progress.at(-1).layouts.reduce((n,l)=>n+l.placements.length,0),12);
for(const layout of result.layouts)for(let i=0;i<layout.placements.length;i++)for(let j=i+1;j<layout.placements.length;j++)assert.equal(shapesOverlap(layout.placements[i].placedShape,layout.placements[j].placedShape,5),false);
const low=fillPolygonSheet({length:1000,width:1000},Array.from({length:10},(_,i)=>({instanceId:'small-'+i,length:100,width:100,allowRotate:false})),{maxPolygonEvaluations:1,sawWidth:5,polygonPlacementStrategy:'bottomLeft'});
assert.equal(low.placements.length,10,'复杂搜索预算耗尽后仍须执行独立的安全补排');
assert.equal(low.diagnostics.evaluations,1);assert.ok(low.diagnostics.completionEvaluations>0);
console.log('Spare-space regression passed: screenshot project 12 parts/1 sheet, independent clearance checks, progressive snapshots and completion after search exhaustion.');
