import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {importCadText} from '../cad-import.mjs';
import {buildCadPreviewScene} from '../cad-preview.mjs';
const parts=importCadText(readFileSync(new URL('../examples/CAD-轮廓与内孔示例.dxf',import.meta.url),'utf8')).parts;
const before=structuredClone(parts),scene=buildCadPreviewScene(parts);
assert.deepEqual(scene.map(e=>e.origin),[[0,-80],[200,-60]]);
assert.equal(scene[1].bounds.minX-scene[0].bounds.maxX,80,'整图保留CAD的件间距离');
assert.equal((scene[0].path.match(/M/g)||[]).length,2,'主轮廓与内孔都要画出');
assert.deepEqual(parts,before,'预览不可移动或改写实际零件轮廓');
const legacy=buildCadPreviewScene([{length:100,width:60},{length:50,width:40}]);
assert.ok(legacy[1].bounds.minX>legacy[0].bounds.maxX,'旧数据无来源坐标时可分开预览');
const duplicate=buildCadPreviewScene(parts.map((part,i)=>({...part,cadSource:{...part.cadSource,fileName:'same.dxf',previewFileId:String(i)}})));
assert.notEqual(duplicate[0].fileId,duplicate[1].fileId);
assert.throws(()=>buildCadPreviewScene([{shape:{outer:[[NaN,0],[1,0],[0,1]],holes:[]}}]),/坐标无效/);
console.log('CAD preview scene tests passed: original placement, holes, immutable parts, legacy fallback and file identities.');
