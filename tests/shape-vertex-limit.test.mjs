import assert from 'node:assert/strict';
import { importCadText } from '../cad-import.mjs';
import { normalizeShape, rotationCandidates } from '../polygon-geometry.mjs';
import { shapeFromEditor, partsFromShapeJson, serializeShapeJson } from '../parts-shapes.mjs';
import { optimizeCuttingPlan, validateProject } from '../engine.mjs';
import { formatQuotationText } from '../quotation.mjs';
const outer = Array.from({length:300},(_,i)=>[100+100*Math.cos(i*Math.PI/150),100+100*Math.sin(i*Math.PI/150)]);
const shape={outer,holes:[]};
assert.ok(rotationCandidates({shape},{rotationStep:15}).length<=152,'密集曲线边方向候选必须有界');
assert.deepEqual(rotationCandidates({shape,rotationAngles:[17.3,91.2]},{}),[17.3,91.2],'显式角度不能被采样丢弃');
const dxf=`0\nSECTION\n2\nENTITIES\n0\nLWPOLYLINE\n90\n300\n70\n1\n${outer.map(([x,y])=>`10\n${x}\n20\n${y}\n`).join('')}0\nENDSEC\n0\nEOF\n`;
assert.throws(()=>importCadText(dxf),/256/);
assert.equal(importCadText(dxf,{maxVertices:512}).parts[0].shape.outer.length,300);
const circle='0\nSECTION\n2\nENTITIES\n0\nCIRCLE\n10\n0\n20\n0\n40\n100\n0\nENDSEC\n0\nEOF\n';
assert.throws(()=>importCadText(circle,{curveTolerance:.001}),/256/);
assert.ok(importCadText(circle,{curveTolerance:.001,maxVertices:2048}).parts[0].shape.outer.length>256);
assert.throws(()=>normalizeShape(shape),/256/);
assert.equal(shapeFromEditor(outer.map(p=>p.join(',')).join('\n'),'',{maxVertices:512}).outer.length,300);
const part={id:'large',shape,quantity:1,length:200,width:200,material:'MDF',thickness:18,allowRotate:false};
assert.throws(()=>serializeShapeJson([part]),/256/);
const text=serializeShapeJson([part],{maxVertices:512});
assert.equal(partsFromShapeJson(text,{maxVertices:512,panels:[{material:'MDF',thickness:18} ]})[0].shape.outer.length,300);
const project={parts:[part],panels:[{length:500,width:500,material:'MDF',thickness:18,cost:100,weight:20}],settings:{maxShapeVertices:512,allowRotation:false,optimizationLevel:'quick'}};
assert.deepEqual(validateProject(project),[]);
assert.equal(optimizeCuttingPlan(project).stats.placedCount,1);
const automatic=optimizeCuttingPlan({...project,parts:[{...part,quantity:8,allowRotate:true}],panels:[{...project.panels[0],length:1220,width:2440}],settings:{...project.settings,allowRotation:true}});
assert.equal(automatic.stats.placedCount,8);
assert.equal(automatic.stats.usedPanels,1,'自动角度细化不能丢掉已生成的一张板方案');
assert.match(formatQuotationText({parts:[part],maxShapeVertices:512}),/200\*200\*18mm 1张/);
assert.throws(()=>formatQuotationText({parts:[part],maxShapeVertices:256}),/256/);
assert.ok(validateProject({...project,settings:{...project.settings,maxShapeVertices:256}}).some(e=>e.includes('256')));
for(const value of [0,2,3.5,Infinity,Number.MAX_SAFE_INTEGER+1]) {
  assert.throws(()=>importCadText(dxf,{maxVertices:value}),/顶点上限/);
  assert.ok(validateProject({...project,settings:{maxShapeVertices:value}}).some(e=>e.includes('顶点上限')));
}
console.log('Custom shape vertex limit tests passed: >256 CAD curves/polylines, editor, JSON, nesting and invalid settings.');
