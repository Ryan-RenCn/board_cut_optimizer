import assert from 'node:assert/strict';
import { importCadText } from '../cad-import.mjs';
const draw=(entities,blocks='')=>`0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n4\n0\nENDSEC\n${blocks?`0\nSECTION\n2\nBLOCKS\n${blocks}0\nENDSEC\n`:''}0\nSECTION\n2\nENTITIES\n${entities}0\nENDSEC\n0\nEOF\n`;
const rectangle='0\nLWPOLYLINE\n90\n4\n70\n1\n10\n0\n20\n0\n10\n100\n20\n0\n10\n100\n20\n60\n10\n0\n20\n60\n';
const solid=(points)=>'0\nSOLID\n'+points.map(([x,y,z=0],i)=>`${10+i}\n${x}\n${20+i}\n${y}\n${30+i}\n${z}\n`).join('');
const fill=solid([[10,10],[30,10],[10,30],[30,30]]);
const plain=importCadText(draw(rectangle));
const mixed=importCadText(draw(rectangle+fill));
assert.deepEqual(mixed.parts[0].shape,plain.parts[0].shape);
assert.equal(mixed.parts.length,1);assert.equal(mixed.parts[0].shape.holes.length,0,'内部填充不能默认变成内孔');
assert.ok(mixed.warnings.some(w=>w.includes('忽略SOLID')));
assert.throws(()=>importCadText(draw(fill)),/只有填充或标注/);
assert.throws(()=>importCadText(draw(fill),{solidMode:'bad'}),/处理方式/);
const outline=importCadText(draw(solid([[0,0],[100,0],[0,60],[100,60]])),{solidMode:'outline'});
assert.deepEqual([outline.parts[0].length,outline.parts[0].width,outline.parts[0].shape.outer.length],[100,60,4]);
assert.equal(outline.parts[0].cadSource.solidMode,'outline');
const tri=importCadText(draw(solid([[0,0],[100,0],[0,60],[0,60]])),{solidMode:'outline'});
assert.equal(tri.parts[0].shape.outer.length,3);
assert.throws(()=>importCadText(draw(solid([[0,0],[100,0],[0,60,1],[100,60]])),{solidMode:'outline'}),/同一XY平面/);
const block=`0\nBLOCK\n2\nARROW\n70\n0\n10\n0\n20\n0\n${fill}0\nENDBLK\n`;
const inserted=importCadText(draw(rectangle+'0\nINSERT\n2\nARROW\n10\n150\n20\n0\n',block));
assert.equal(inserted.parts.length,1,'块中的SOLID箭头不应变成额外零件');
const transformed=importCadText(draw('0\nINSERT\n2\nARROW\n10\n150\n20\n0\n41\n2\n42\n3\n50\n90\n',block),{solidMode:'outline'});
assert.ok(Math.abs(transformed.parts[0].length-60)<1e-6);assert.ok(Math.abs(transformed.parts[0].width-40)<1e-6);
assert.throws(()=>importCadText(draw(rectangle+'0\nREGION\n')),/不支持的CAD图元/);
console.log('CAD SOLID tests passed: ignore fill/arrows, no false holes, explicit triangle/quadrilateral boundary, block transforms, source and nonplanar rejection.');
