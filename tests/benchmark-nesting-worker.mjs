import { parentPort, workerData } from 'node:worker_threads';
import assert from 'node:assert/strict';
import { shapesOverlap } from './fixtures/polygon-geometry-reference.mjs';
const { optimizeCuttingPlan } = await import(workerData.enginePath || '../engine.mjs');
const {vertices,quantity,holes}=workerData;
const ring=(rx,ry)=>Array.from({length:vertices},(_,i)=>[rx+rx*Math.cos(i*2*Math.PI/vertices),ry+ry*Math.sin(i*2*Math.PI/vertices)]);
const shape={outer:ring(100,70),holes:holes?[ring(30,20).map(([x,y])=>[x+60,y+40])]:[]};
const settings={sawWidth:3,panelMarginX:10,panelMarginY:10,allowRotation:true,rotationStep:15,maxShapeVertices:vertices*2,optimizationLevel:'quick'};
const start=performance.now();
const result=optimizeCuttingPlan({settings,parts:[{id:'a',shape,quantity,length:200,width:140,material:'MDF',thickness:18,...(workerData.autoRotate?{}:{rotationAngles:[0]})}],panels:[{length:1220,width:2440,material:'MDF',thickness:18,cost:100,weight:40}]});
const ms=Math.round(performance.now()-start);
for(const layout of result.layouts)for(let i=0;i<layout.placements.length;i++)for(let j=i+1;j<layout.placements.length;j++)assert.equal(shapesOverlap(layout.placements[i].placedShape,layout.placements[j].placedShape,settings.sawWidth),false);
assert.equal(result.stats.placedCount,quantity);
parentPort.postMessage({ms,placed:result.stats.placedCount,panels:result.stats.usedPanels,usage:result.stats.partsArea,geometryVerified:true});
